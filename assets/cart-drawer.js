const trigger = document.querySelector("[data-cart-trigger]");
const drawer = document.querySelector("[data-cart-drawer]");

if (trigger && drawer) {
  trigger.addEventListener("click", () => {
    const aberto = trigger.getAttribute("aria-expanded") === "true";
    trigger.setAttribute("aria-expanded", String(!aberto));
    drawer.hidden = aberto;
    if (!aberto) drawer.querySelector("a, button")?.focus();
  });
}
